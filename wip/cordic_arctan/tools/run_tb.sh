#!/usr/bin/env bash
#----------------------------------------------------------------------------
# Script : run_tb.sh
# Purpose: compile and run one self-checking XSim testbench from tb/.
#
#   tools/run_tb.sh <tb_name> [xsim args...]
#
#   tools/run_tb.sh tb_cordic_arctan
#   tools/run_tb.sh tb_cordic_arctan --testplusarg DUMP_CSV   (per-config CSV)
#   DUMP=1 tools/run_tb.sh tb_cordic_arctan                   (`define DUMP -> VCD)
#   make tb                                                   (every tb/tb_*.v)
#   make tb TB=tb_cordic_arctan [XSIM_ARGS="--testplusarg QUICK"]
#
# What it does
#   * sources the Vivado settings ($VIVADO_SETTINGS, default
#     /tools/2025.2/Vivado/settings64.sh) when xvlog is not on PATH,
#   * compiles ONLY the RTL each bench needs (the case below is the list -
#     never dot11 & co), the bench itself and, where a bench compares
#     against a Xilinx IP, the IP funcsim netlist (xelab -L unisims_ver, glbl
#     as second top). The cmpy netlist's wrapper module is called
#     complex_multiplier, which clashes with our replacement of the same
#     name, so it is copied into the build directory with the wrapper
#     renamed to cmpy_xilinx_ref (anchored sed on the "module" line only;
#     the inner, encrypted modules keep their names),
#   * runs in build/tb/<tb>/ (fresh xsim.dir each time), writes
#     build/tb/<tb>/<tb>.log and exits non-zero unless the log holds a
#     "RESULT: PASS" line and no "RESULT: FAIL" line.
#
# Every source file gets its own xvlog call: xvlog keeps `define macros
# across the files of one invocation, so an include guard (cordic_arctan.vh
# has one) would hide the include from every file after the first.
#
# Notes for bench authors
#   * -i <rtl dir> is passed to every xvlog call (`include "x.vh" resolves).
#   * LUT_DIR="<rtl dir>" is defined for the benches that pull lut_roms.v.
#   * The funcsim netlists carry `timescale 1ps/1ps and their own glbl with
#     ROC_WIDTH = 100000 ps: Xilinx primitives are held in reset for the
#     first 100 ns of simulated time - do not stimulate the IP before that.
#   * The IP netlists are regenerated by `make check` (gitignored); the
#     script tells you which one is missing.
#
# Environment overrides (mainly for A/B experiments):
#   RTL_DIR (default <repo>/verilog), TB_DIR (<repo>/tb), IP_DIR (<repo>/ip_repo)
#
